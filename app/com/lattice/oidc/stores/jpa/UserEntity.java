package com.lattice.oidc.stores.jpa;

import com.lattice.oidc.common.JsonHelpers;
import com.lattice.oidc.models.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * A row of {@code users} (conf/db/migration/V1__storage.sql). The JSON columns are kept as their
 * text and converted with {@link JsonHelpers}, so values read back exactly as the JDBC store read
 * them. Writes go through {@link JpaUserStore}'s statements, so only {@link #toUser} is used here.
 */
@Entity
@Table(name = "users")
public class UserEntity {

  @Id
  @Column(name = "subject")
  private String subject;

  @Column(name = "login_id")
  private String loginId;

  @Column(name = "password_hash")
  private String passwordHash;

  @JdbcTypeCode(SqlTypes.JSON)
  @Column(name = "claims", nullable = false)
  private String claims;

  @JdbcTypeCode(SqlTypes.JSON)
  @Column(name = "attributes", nullable = false)
  private String attributes;

  @JdbcTypeCode(SqlTypes.JSON)
  @Column(name = "verified_claims", nullable = false)
  private String verifiedClaims;

  /** Generated by PostgreSQL from claims: lower(claims ->> 'email'). */
  @Column(name = "email", insertable = false, updatable = false)
  private String email;

  /** Generated by PostgreSQL from claims: claims ->> 'phone_number'. */
  @Column(name = "phone_number", insertable = false, updatable = false)
  private String phoneNumber;

  @Column(name = "created_at", nullable = false, insertable = false, updatable = false)
  private Instant createdAt;

  @Column(name = "updated_at", nullable = false, insertable = false)
  private Instant updatedAt;

  /** For JPA. */
  protected UserEntity() {}

  @SuppressWarnings("unchecked")
  User toUser() {
    return new User(
        subject,
        loginId,
        passwordHash,
        JsonHelpers.readMap(claims),
        JsonHelpers.readMap(attributes),
        (List<Map<String, Object>>) (List<?>) JsonHelpers.readList(verifiedClaims));
  }
}
