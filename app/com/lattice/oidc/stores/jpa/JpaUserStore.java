package com.lattice.oidc.stores.jpa;

import com.lattice.oidc.common.JsonHelpers;
import com.lattice.oidc.common.LatticeConfig;
import com.lattice.oidc.models.User;
import com.lattice.oidc.stores.InMemoryUserStore;
import com.lattice.oidc.stores.UserStore;
import jakarta.inject.Inject;
import jakarta.inject.Singleton;
import java.util.List;
import java.util.Optional;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import play.Environment;

/**
 * {@link UserStore} in PostgreSQL through JPA (entity {@link UserEntity}, table {@code users}). With
 * {@code lattice.demo-users} on, the demo accounts are added only to an empty table, so a real
 * database is never changed.
 */
@Singleton
public final class JpaUserStore implements UserStore {

  private static final Logger LOG = LoggerFactory.getLogger(JpaUserStore.class);

  private final JpaDatabase database;

  @Inject
  public JpaUserStore(JpaDatabase database, LatticeConfig config, Environment environment) {
    this.database = database;
    if (config.demoUsers() && count() == 0) {
      List<User> demo = InMemoryUserStore.demoUsers(environment);
      demo.forEach(this::save);
      LOG.warn("Seeded {} DEMO user accounts into an empty database; disable lattice.demo-users in production.", demo.size());
    }
  }

  @Override
  public Optional<User> bySubject(String subject) {
    if (subject == null) {
      return Optional.empty();
    }
    return database.transaction(em -> Optional.ofNullable(em.find(UserEntity.class, subject)).map(UserEntity::toUser));
  }

  @Override
  public Optional<User> byLoginId(String loginId) {
    if (loginId == null) {
      return Optional.empty();
    }
    return database.transaction(
        em ->
            em.createQuery("select u from UserEntity u where lower(u.loginId) = lower(:loginId)", UserEntity.class)
                .setParameter("loginId", loginId)
                .getResultStream()
                .findFirst()
                .map(UserEntity::toUser));
  }

  @Override
  public Optional<User> byEmail(String email) {
    if (email == null) {
      return Optional.empty();
    }
    // email is generated by PostgreSQL as lower(claims ->> 'email').
    return database.transaction(
        em ->
            em.createQuery("select u from UserEntity u where u.email = lower(:email) order by u.subject", UserEntity.class)
                .setParameter("email", email)
                .setMaxResults(1)
                .getResultStream()
                .findFirst()
                .map(UserEntity::toUser));
  }

  @Override
  public Optional<User> byPhoneNumber(String phoneNumber) {
    if (phoneNumber == null) {
      return Optional.empty();
    }
    return database.transaction(
        em ->
            em.createQuery(
                    "select u from UserEntity u where u.phoneNumber = :phoneNumber order by u.subject", UserEntity.class)
                .setParameter("phoneNumber", phoneNumber)
                .setMaxResults(1)
                .getResultStream()
                .findFirst()
                .map(UserEntity::toUser));
  }

  @Override
  public void save(User user) {
    // Native SQL: an upsert is one atomic statement in PostgreSQL. JPA's merge would read, then insert
    // or update, and two concurrent saves of a new user would both try to insert.
    database.transaction(
        em ->
            em.createNativeQuery(
                    """
                    INSERT INTO users (subject, login_id, password_hash, claims, attributes, verified_claims)
                    VALUES (?1, ?2, ?3, CAST(?4 AS jsonb), CAST(?5 AS jsonb), CAST(?6 AS jsonb))
                    ON CONFLICT (subject) DO UPDATE SET
                      login_id = EXCLUDED.login_id, password_hash = EXCLUDED.password_hash, claims = EXCLUDED.claims,
                      attributes = EXCLUDED.attributes, verified_claims = EXCLUDED.verified_claims, updated_at = now()
                    """)
                .setParameter(1, user.getSubject())
                .setParameter(2, user.loginId())
                .setParameter(3, user.passwordHash())
                .setParameter(4, JsonHelpers.write(user.claims()))
                .setParameter(5, JsonHelpers.write(user.attributes()))
                .setParameter(6, JsonHelpers.write(user.verifiedClaims()))
                .executeUpdate());
  }

  @Override
  public boolean replacePasswordHash(String subject, String expectedHash, String newHash) {
    if (subject == null || expectedHash == null || newHash == null) {
      return false;
    }
    // One statement (a JPQL bulk update): the row changes only if its hash is still the one that
    // was verified.
    return database.transaction(
            em ->
                em.createQuery(
                        """
                        update UserEntity u set u.passwordHash = :newHash, u.updatedAt = instant
                        where u.subject = :subject and u.passwordHash = :expectedHash
                        """)
                    .setParameter("newHash", newHash)
                    .setParameter("subject", subject)
                    .setParameter("expectedHash", expectedHash)
                    .executeUpdate())
        == 1;
  }

  @Override
  public long count() {
    return database.transaction(em -> em.createQuery("select count(u) from UserEntity u", Long.class).getSingleResult());
  }
}
